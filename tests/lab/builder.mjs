// A new trail is two questions; its settings are one explained panel.
import { browser, BASE, SHOTS, check, done, makeUser, cleanUsers, signIn, sql } from './lib.mjs';
const b = await browser();
const errs = [];
try {
  const u = await makeUser('builder');
  const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
  p.on('pageerror', (e) => errs.push(e.message));
  p.on('dialog', (d) => d.accept().catch(() => {}));
  await signIn(p, u);
  await p.goto(`${BASE}/my-trails/?new=1`);
  await p.waitForSelector('[data-create]:not([hidden])', { timeout: 15000 });
  const legends = await p.$$eval('[data-create] legend', (l) => l.map((x) => x.textContent.trim()));
  check('new trail asks two questions', legends.length === 2 && legends[0].includes('точки') && legends[1].includes('ред'), legends.join(' | '));
  await p.screenshot({ path: `${SHOTS}/new-trail.png` });
  await p.fill('[data-new-name]', 'Лаб тест без точки');
  await p.click('label:has(input[name=scored][value=no])');
  await p.click('[data-create-submit]');
  await p.waitForURL(/trail/, { timeout: 20000 });
  const [w] = await sql(`select id, mode from worlds where owner_id = $1`, [u.id]);
  check('no points + in order = guide', w?.mode === 'guide', w?.mode);
  await p.waitForSelector('[data-trail-mode]', { timeout: 15000 });
  await p.waitForTimeout(2500);
  check('builder shows the plain line', (await p.textContent('[data-trail-mode]')) === 'Без точки · По ред');
  check('settings start folded', !(await p.$eval('[data-settings]', (d) => d.open)));
  check('summary names the start', (await p.textContent('[data-settings-sum]')).includes('Старт'));
  await p.click('[data-settings] summary');
  check('team size hidden on a no-points trail', !(await p.isVisible('[data-team-row]')));
  check('one-at-a-time shown on an ordered trail', await p.isVisible('[data-reveal-row]'));
  check('help is visible text, not a tooltip', await p.isVisible('[data-settings] .set-hint'));
  await p.fill('[data-finish-bonus]', '120'); await p.press('[data-finish-bonus]', 'Tab');
  await p.waitForTimeout(1500);
  const [w2] = await sql(`select finish_bonus_xp from worlds where id = $1`, [w.id]);
  check('bonus saves', w2.finish_bonus_xp === 120, String(w2.finish_bonus_xp));
  check('summary updates', (await p.textContent('[data-settings-sum]')).includes('+120 XP'));
  await p.screenshot({ path: `${SHOTS}/builder-settings.png` });
  await p.goto(`${BASE}/en/my-trails/?new=1`);
  await p.waitForSelector('[data-create]:not([hidden])', { timeout: 15000 });
  await p.fill('[data-new-name]', 'Lab points any order');
  await p.click('label:has(input[name=ordered][value=no])');
  await p.click('[data-create-submit]');
  await p.waitForURL(/trail/, { timeout: 20000 });
  await p.waitForTimeout(2500);
  const rows = await sql(`select mode from worlds where owner_id = $1 order by created_at`, [u.id]);
  check('points + any order = freefall', rows[1]?.mode === 'freefall', rows[1]?.mode);
  await p.click('[data-settings] summary');
  check('team size shown on a points trail', await p.isVisible('[data-team-row]'));
  check('one-at-a-time hidden with no order', !(await p.isVisible('[data-reveal-row]')));
  await p.goto(`${BASE}/my-trails/`);
  await p.waitForSelector('[data-card]', { timeout: 15000 });
  const guideCard = `[data-card="${w.id}"]`, ffCard = `[data-card]:not([data-card="${w.id}"])`;
  check('card shows the plain line', (await p.textContent(guideCard)).includes('Без точки · По ред'));
  check('no standings button on a no-points trail', !(await p.$(`${guideCard} a[href*="/board"]`)));
  check('standings button on a points trail', !!(await p.$(`${ffCard} a[href*="/board"]`)));
  check('no trail page while private', !(await p.$(`${guideCard} a[href*="/view"]`)));
  await p.screenshot({ path: `${SHOTS}/my-trails.png`, fullPage: true });
  const ph = await b.newPage({ viewport: { width: 390, height: 844 } });
  await signIn(ph, u);
  await ph.goto(`${BASE}/trail/?id=${w.id}`);
  await ph.waitForSelector('[data-trail-mode]', { timeout: 15000 });
  await ph.waitForTimeout(2500);
  const sw = await ph.evaluate(() => document.documentElement.scrollWidth);
  check('builder on a phone: no horizontal scroll', sw <= 390, String(sw));
  await ph.screenshot({ path: `${SHOTS}/builder-phone.png`, fullPage: true });
} finally {
  await cleanUsers();
  await b.close();
}
check('no page errors', errs.length === 0, errs.slice(0, 3).join(' | '));
done();
